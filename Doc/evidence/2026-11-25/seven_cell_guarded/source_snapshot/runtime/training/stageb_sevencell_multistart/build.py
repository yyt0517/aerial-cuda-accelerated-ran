"""Build an isolated solver whose optional warm start is always adopted."""
import difflib
from pathlib import Path
import subprocess
from training.stageb_ppo.native import sha, write

def main():
    here=Path(__file__).parent;source=here.parent/'stageb_sevencell';dest=here/'kernel';dest.mkdir(exist_ok=True)
    diffs=[]
    for name in ('physics_kernel.cpp','persistent_kernel.cpp','bounded_kernel.cpp'):
        original=(source/'kernel'/name).read_text();text=original
        if name=='persistent_kernel.cpp':
            old='if(d>=floor&&j>score){action.assign(warm,warm+p.C*p.P);values.swap(v);totals();}'
            new='if(d<floor)throw std::runtime_error("Forced start violates raw PFQ floor");\n            action.assign(warm,warm+p.C*p.P);values.swap(v);totals();'
            assert text.count(old)==1;text=text.replace(old,new)
        (dest/name).write_text(text)
        diffs.extend(difflib.unified_diff(original.splitlines(True),text.splitlines(True),fromfile=str(source/'kernel'/name),tofile=name))
    (dest/'forced_start.diff').write_text(''.join(diffs))
    text=(source/'solver.py').read_text().replace('from .contract import check_contract','from training.stageb_sevencell.contract import check_contract')
    text=text.replace('_bounded128.so','_seeded.so').replace("version='capacity_bound_q1e6_v1'","version='forced_start_capacity_bound_q1e6_v1'")
    (here/'seeded_solver.py').write_text('"""Generated by build.py; warm_start is forced, PFQ floor is unchanged."""\n'+text)
    command=['g++','-O3','-std=c++17','-DNDEBUG','-ffp-contract=off','-fno-fast-math','-shared','-fPIC','-Wl,-Bsymbolic','-I/usr/include/eigen3','-I/usr/local/include/eigen3',str(dest/'bounded_kernel.cpp'),'-o',str(here/'_seeded.so')]
    subprocess.run(command,check=True)
    write(dest/'manifest.json',dict(source={n:sha(source/'kernel'/n) for n in ('physics_kernel.cpp','persistent_kernel.cpp','bounded_kernel.cpp')},
        modified={p.name:sha(p) for p in dest.glob('*.cpp')},library_sha256=sha(here/'_seeded.so'),command=command,
        scope='Only force adoption of supplied feasible initial action; floor remains based on raw PFQ; no search/PHY changes'))

if __name__=='__main__':main()
